const FILLED = new Set(['ribbon']);

export function icon(name, { filled = FILLED.has(name), label = '' } = {}) {
  const body = PATHS[name] || '';
  const cls = filled ? 'ico ico-fill' : 'ico';
  const a11y = label ? `role="img" aria-label="${label}"` : 'aria-hidden="true" focusable="false"';
  return `<svg class="${cls}" viewBox="0 0 24 24" ${a11y}>${body}</svg>`;
}

/** Replace every <span data-icon="name"> placeholder under root with its SVG. */
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll('[data-icon]')) {
    if (el.firstElementChild) continue;
    el.innerHTML = icon(el.dataset.icon);
  }
}
